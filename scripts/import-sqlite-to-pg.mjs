/*
 * One-time migration: SQLite (data/podiumset.db) -> Supabase/Postgres.
 *
 * Usage (direct connection):
 *   DATABASE_URL=postgres://... node scripts/import-sqlite-to-pg.mjs
 *
 * Usage (no direct connection available - emits a SQL file to paste into
 * the Supabase dashboard's SQL Editor):
 *   node scripts/import-sqlite-to-pg.mjs --sql data/import.sql
 *
 * Usage (direct connection + create the schema first):
 *   DATABASE_URL=postgres://... node scripts/import-sqlite-to-pg.mjs --create-schema
 *
 * Reads every table from the SQLite file, re-inserts rows with the same
 * ids into Postgres, then fixes the serial sequences.
 */
import Database from "better-sqlite3";
import fs from "node:fs";

const SQLITE_PATH = process.env.SQLITE_PATH || "data/podiumset.db";
const SQL_OUT = process.argv.includes("--sql")
  ? process.argv[process.argv.indexOf("--sql") + 1]
  : null;
const CREATE_SCHEMA = process.argv.includes("--create-schema");
const SCHEMA_PATH = "data/schema.sql";

if (!fs.existsSync(SQLITE_PATH)) {
  console.error(`SQLite file not found: ${SQLITE_PATH}`);
  process.exit(1);
}
if (!SQL_OUT && !process.env.DATABASE_URL) {
  console.error("DATABASE_URL is required (or use --sql <outfile>)");
  process.exit(1);
}

const sql = new Database(SQLITE_PATH, { readonly: true });
const { Pool } = await import("pg");
let pool;
if (!SQL_OUT) {
  try {
    pool = new Pool({
      connectionString: process.env.DATABASE_URL,
      ssl: { rejectUnauthorized: false },
    });
    await pool.query("SELECT 1");
    console.log("Connected to Postgres.");
  } catch (e) {
    console.error("Cannot connect to Postgres:", e.message);
    process.exit(1);
  }
  if (CREATE_SCHEMA) {
    if (!fs.existsSync(SCHEMA_PATH)) {
      console.error(`Schema file not found: ${SCHEMA_PATH}`);
      process.exit(1);
    }
    const ddl = fs
      .readFileSync(SCHEMA_PATH, "utf8")
      .split(";")
      .map((s) => s.trim())
      .filter(Boolean);
    for (const stmt of ddl) {
      try {
        await pool.query(stmt);
      } catch (e) {
        console.error(`DDL FAIL: ${e.message}\n  ${stmt.slice(0, 80)}...`);
        process.exit(1);
      }
    }
    console.log(`Schema applied (${ddl.length} statements).`);
  }
}

function pgLiteral(v) {
  if (v == null) return "NULL";
  if (typeof v === "number" || typeof v === "bigint")
    return Number.isInteger(Number(v)) ? String(v) : String(Number(v));
  const s = Buffer.isBuffer(v) ? String(v) : String(v);
  return "'" + s.replaceAll("'", "''") + "'";
}

// Topological order: parents first so FK references resolve.
const TABLES = [
  "plan",
  "addon",
  "request_type",
  "account",
  "user",
  "phase",
  "subscription",
  "subscription_addon",
  "payment",
  "request",
  "subtask",
  "deliverable",
  "comment",
  "attachment",
  "brand_profile",
  "email_verify",
  "entitlement_log",
  "notification",
  "ads_update",
];

let total = 0;
if (SQL_OUT) {
  // Emit a self-contained SQL script (no network needed).
  const out = [];
  out.push("-- Generated by scripts/import-sqlite-to-pg.mjs");
  out.push("-- Paste into Supabase Dashboard -> SQL Editor and run.");
  out.push("BEGIN;");
  for (const table of TABLES) {
    const cols = sql
      .prepare(`PRAGMA table_info(${table})`)
      .all()
      .map((c) => c.name);
    if (cols.length === 0) {
      console.log(`skip ${table}: not present`);
      continue;
    }
    const rows = sql.prepare(`SELECT * FROM ${table}`).all();
    if (rows.length === 0) {
      console.log(`${table}: 0 rows (skip)`);
      continue;
    }
    const colSql = cols.map((c) => `"${c}"`).join(", ");
    for (const r of rows) {
      const vals = cols.map((c) => {
        let v = r[c];
        if (typeof v === "bigint") v = Number(v);
        if (Buffer.isBuffer(v)) v = String(v);
        return v;
      });
      out.push(
        `INSERT INTO public."${table}" (${colSql}) VALUES (${vals
          .map(pgLiteral)
          .join(", ")});`
      );
    }
    const maxId = Number(
      sql.prepare(`SELECT COALESCE(MAX(id), 0) AS m FROM ${table}`).get().m ?? 0
    );
    if (maxId > 0) {
      out.push(
        `SELECT setval(pg_get_serial_sequence('public."${table}"', 'id'), ${maxId});`
      );
    }
    total += rows.length;
    console.log(`${table}: ${rows.length} rows queued`);
  }
  out.push("COMMIT;");
  fs.writeFileSync(SQL_OUT, out.join("\n"), "utf8");
  console.log(`\nSQL file written: ${SQL_OUT} (${total} rows)`);
  process.exit(0);
}

for (const table of TABLES) {
  const cols = sql
    .prepare(`PRAGMA table_info(${table})`)
    .all()
    .map((c) => c.name);
  if (cols.length === 0) {
    console.log(`skip ${table}: not present`);
    continue;
  }
  const rows = sql.prepare(`SELECT * FROM ${table}`).all();
  if (rows.length === 0) {
    console.log(`${table}: 0 rows (skip)`);
    continue;
  }

  for (const r of rows) {
    const vals = cols.map((c) => {
      let v = r[c];
      if (v == null) return null;
      if (typeof v === "bigint") return Number(v);
      if (Buffer.isBuffer(v)) return String(v);
      return v;
    });
    const placeholders = cols.map((_, i) => `$${i + 1}`).join(", ");
    const q = `INSERT INTO public."${table}" (${cols
      .map((c) => `"${c}"`)
      .join(", ")}) VALUES (${placeholders})`;
    try {
      await pool.query(q, vals);
      total++;
    } catch (e) {
      console.error(`FAIL ${table} id=${r.id}: ${e.message}`);
    }
  }

  const { rows: mx } = await pool.query(
    `SELECT COALESCE(MAX(id), 0) AS m FROM public."${table}"`
  );
  const maxId = Number(mx[0]?.m ?? 0);
  if (maxId > 0) {
    await pool.query(
      `SELECT setval(pg_get_serial_sequence('public."${table}"', 'id'), $1)`,
      [maxId]
    );
  }
  console.log(`${table}: ${rows.length} imported, max id ${maxId}`);
}

await pool.end();
console.log(`\nDONE — ${total} rows imported.`);